"""Dataset + collator for SFT.

Reads the JSONL produced by `sft.generate_data` and turns each (problem,
completion) pair into a tokenized example: the [system, user] prompt rendered
with the student tokenizer's chat template, followed by the assistant turn the
student must learn to emit.

The split matters because gpt-oss speaks HARMONY, in which an assistant turn is

    <|start|>assistant<|channel|>final<|message|>…<|return|>

and everything from `<|channel|>` onwards is GENERATED by the model — the
channel header is part of the completion, not of the prompt. `apply_chat_template`
on a [system, user, assistant] conversation does NOT render it: the gpt-oss
template only emits `<|channel|>` for an assistant message carrying a separate
`thinking` field, and otherwise falls back to a bare
`<|start|>assistant<|message|>…`. Training on that fallback teaches the student to
open its turn with `<|message|>`, a sequence that never occurs in harmony, and
vLLM's harmony parser then has no channel to attribute the text to and returns
`content: null` — i.e. the trained checkpoint answers nothing at all through the
serving path (measured on sft/checkpoints/20260730-234029 after one epoch).
`_render` therefore builds the assistant turn explicitly.

The loss is the next-token language-modeling loss over the target tokens, and —
unless SFT_MASK_PROMPT=1 — over the prompt tokens as well; `pad` positions are
always ignored.
"""
from __future__ import annotations

import json
import random
from pathlib import Path

import torch
from torch.utils.data import Dataset

from pipeline.prompts import serving_prompt_ids
from pipeline.utils import logger

from . import config

# Harmony control tokens. Their presence is what tells us the student speaks
# harmony (gpt-oss) and the assistant turn has to be built by hand; a tokenizer
# without them falls back to the plain chat-template render.
_CHANNEL, _MESSAGE, _RETURN = "<|channel|>", "<|message|>", "<|return|>"


def load_records(jsonl_path: str) -> list[dict]:
    """Read the distillation JSONL into a list of raw records.

    Each record carries at least `problem`, `answer` (ground truth) and
    `completion`; downstream, training tokenizes (problem → completion) while the
    held-out validation split generates from `problem` and grades against `answer`.
    """
    path = Path(jsonl_path)
    if not path.exists():
        raise FileNotFoundError(
            f"{jsonl_path} not found. Run `python -m sft.generate_data` first."
        )
    records = [
        json.loads(line)
        for line in (ln.strip() for ln in path.read_text().splitlines())
        if line
    ]
    if not records:
        raise ValueError(f"No examples loaded from {jsonl_path}.")
    n_no_reasoning = sum(1 for r in records if "<reasoning>" not in r.get("completion", ""))
    if n_no_reasoning:
        logger.warning(
            "%d / %d records in %s have no <reasoning> block — the student will be "
            "trained to answer without thinking on those. Regenerate them with "
            "`python -m sft.generate_data`.",
            n_no_reasoning, len(records), jsonl_path,
        )
    return records


def split_records(
    records: list[dict], val_frac: float, seed: int, val_cap: int = 0
) -> tuple[list[dict], list[dict]]:
    """Shuffle (deterministically) and hold out `val_frac` of records for validation.

    `val_frac` <= 0 keeps everything for training (no validation). `val_cap` > 0
    caps the validation set size so per-epoch generation stays cheap; the capped-off
    remainder goes back into training rather than being discarded.
    """
    if val_frac <= 0:
        return records, []
    shuffled = records[:]
    random.Random(seed).shuffle(shuffled)
    n_val = int(len(shuffled) * val_frac)
    if val_cap > 0:
        n_val = min(n_val, val_cap)
    return shuffled[n_val:], shuffled[:n_val]


def _speaks_harmony(tokenizer) -> bool:
    """True if the tokenizer knows the harmony control tokens (i.e. this is gpt-oss)."""
    unk = getattr(tokenizer, "unk_token_id", None)
    for token in (_CHANNEL, _MESSAGE, _RETURN):
        tid = tokenizer.convert_tokens_to_ids(token)
        if tid is None or (unk is not None and tid == unk):
            return False
    return True


def _prompt_ids(tokenizer, problem: str) -> list[int]:
    """Tokenize [system, user] plus the assistant-turn opening (what vLLM sends).

    Rendered through `pipeline.prompts.serving_prompt_ids` rather than the chat
    template directly, so the student is trained on the byte-identical prompt its
    checkpoint is later served under — the template adds a tools sentence the
    server never sends, and stamps a date the server re-derives per request.
    """
    return serving_prompt_ids(
        config.SYSTEM_PROMPT, problem, tokenizer, model_path=config.STUDENT_MODEL
    )


def _render(tokenizer, problem: str, completion: str) -> tuple[list[int], list[int]]:
    """Tokenize one example as (prompt_ids, target_ids).

    `prompt_ids` ends exactly where inference starts — for gpt-oss at
    `<|start|>assistant`, since add_generation_prompt=True renders the same prefix
    vLLM builds for a chat request. `target_ids` is what the model must generate:

        <|channel|>final<|message|>{completion}<|return|>

    i.e. the teacher trace delivered on harmony's `final` channel and terminated
    by `<|return|>`, which is what makes the served checkpoint parse (channel
    present) and stop (`<|return|>` is an eos id in generation_config.json). The
    trace keeps its `<reasoning>…</reasoning><answer>…</answer>` tags inside that
    message — the format config.SYSTEM_PROMPT asks for and every consumer in this
    repo (inference_script._parse_output, the graders, the benchmarks) reads.

    A tokenizer that doesn't speak harmony falls back to the stock chat-template
    render of the full [system, user, assistant] conversation, with the target
    taken as whatever it appends past the prompt.
    """
    prompt_ids = _prompt_ids(tokenizer, problem)

    if _speaks_harmony(tokenizer):
        target_ids = tokenizer.encode(
            f"{_CHANNEL}final{_MESSAGE}{completion}{_RETURN}", add_special_tokens=False
        )
        return prompt_ids, list(target_ids)

    full = tokenizer.apply_chat_template(
        [
            {"role": "system", "content": config.SYSTEM_PROMPT},
            {"role": "user", "content": problem},
            {"role": "assistant", "content": completion},
        ],
        tokenize=True,
        add_generation_prompt=False,
        return_tensors=None,
    )
    if hasattr(full, "input_ids"):
        full = full["input_ids"]
    full = list(full)
    if full[: len(prompt_ids)] != prompt_ids:
        # The template renders the assistant turn without keeping the generation
        # prompt as a prefix; we can't locate the boundary, so supervise the whole
        # sequence (and mask nothing).
        return [], full
    return prompt_ids, full[len(prompt_ids):]


class SFTDataset(Dataset):
    """Tokenized (problem → teacher solution) examples for causal-LM SFT."""

    def __init__(self, records: list[dict], tokenizer, max_seq_len: int,
                 mask_prompt: bool = False):
        self.tokenizer = tokenizer
        self.max_seq_len = max_seq_len
        self.examples: list[dict] = []

        n_truncated = n_skipped = 0
        for rec in records:
            prompt_ids, target_ids = _render(tokenizer, rec["problem"], rec["completion"])
            if len(prompt_ids) >= max_seq_len:
                # Nothing of the answer would survive; a fully-masked example would
                # also make the loss NaN under mask_prompt. Drop it and say so.
                n_skipped += 1
                continue
            ids = prompt_ids + target_ids
            if len(ids) > max_seq_len:
                # Truncation drops the tail — the <answer> block and the closing
                # <|return|>. Keep that last token so the example still supervises
                # stopping rather than teaching the model to run on forever.
                ids = ids[: max_seq_len - 1] + [ids[-1]]
                n_truncated += 1
            labels = list(ids)
            if mask_prompt:
                labels[: len(prompt_ids)] = [-100] * len(prompt_ids)
            self.examples.append({"input_ids": ids, "labels": labels})

        if not self.examples:
            raise ValueError("No SFT training examples after the train/val split.")
        logger.info(
            "Tokenized %d SFT examples (%d truncated to max_seq_len=%d, %d dropped for "
            "an over-long prompt; prompt tokens %s).",
            len(self.examples), n_truncated, max_seq_len, n_skipped,
            "masked" if mask_prompt else "supervised",
        )

    def __len__(self) -> int:
        return len(self.examples)

    def __getitem__(self, idx: int) -> dict:
        return self.examples[idx]


class SFTCollator:
    """Right-pads a batch; pad positions are ignored in the loss (label -100)."""

    def __init__(self, pad_token_id: int):
        self.pad_token_id = pad_token_id

    def __call__(self, batch: list[dict]) -> dict:
        max_len = max(len(ex["input_ids"]) for ex in batch)
        input_ids, attention_mask, labels = [], [], []
        for ex in batch:
            ids = ex["input_ids"]
            pad = max_len - len(ids)
            input_ids.append(ids + [self.pad_token_id] * pad)
            attention_mask.append([1] * len(ids) + [0] * pad)
            labels.append(ex["labels"] + [-100] * pad)
        return {
            "input_ids": torch.tensor(input_ids, dtype=torch.long),
            "attention_mask": torch.tensor(attention_mask, dtype=torch.long),
            "labels": torch.tensor(labels, dtype=torch.long),
        }
